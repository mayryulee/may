import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const clientsDir = resolve(root, "clients");
const outDir = resolve(root, "packages/shared/generated");
const outTs = resolve(outDir, "client-registry.ts");
const outManifest = resolve(outDir, "client-manifest.json");
const outLoaders = resolve(outDir, "client-loaders.ts");
/** 기본 미리보기 클라이언트 (src/client-route.ts 의 /grace 매핑과 동일하게 유지) */
const DEFAULT_CLIENT_ID = "sample01";
/**
 * 고객 slug 로 쓸 수 없는 주소 — 테마 미리보기(/grace /tender /veil)와 사이트 폴더(public/, dist/)
 * 겹치면 미리보기 페이지를 덮어쓰거나 사진·음원 경로가 깨짐
 */
const RESERVED_SLUGS = new Set([
  "grace", "tender", "veil",
  "assets", "images", "audio", "fonts", "theme-assets", "icons", "api",
]);
const SLUG_PATTERN = /^[a-z0-9][a-z0-9_-]*$/;

function configVarName(id) {
  return `client_${id.replace(/[^a-zA-Z0-9_]/g, "_")}`;
}

/** expiresAt("YYYY-MM-DD") 그날 한국시간 자정까지 유효. 형식이 아니면(미입력·"YYYY-MM-DD") 만료 없음 */
function expiryEndMs(expiresAt) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(expiresAt)) return null;
  const ms = Date.parse(`${expiresAt}T23:59:59.999+09:00`);
  return Number.isNaN(ms) ? null : ms;
}

function readClientField(src, field) {
  const match = src.match(new RegExp(`${field}:\\s*"([^"]*)"`));
  return match?.[1] ?? "";
}

function readClientMeta(src) {
  const metaBlock = src.match(/meta:\s*\{([\s\S]*?)\n\s*\},/)?.[1] ?? "";
  const pick = (field) => {
    const match = metaBlock.match(new RegExp(`${field}:\\s*"([^"]*)"`));
    return match?.[1] ?? "";
  };
  return {
    title: pick("title"),
    description: pick("description"),
    ogSiteName: pick("ogSiteName"),
    ogTitle: pick("ogTitle"),
    ogDescription: pick("ogDescription"),
    ogImage: pick("ogImage") || "cover.png",
    ogImageAlt: pick("ogImageAlt"),
    twitterTitle: pick("twitterTitle"),
    twitterDescription: pick("twitterDescription"),
  };
}

function listClientIds() {
  return readdirSync(clientsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name !== "_template")
    .map((entry) => entry.name)
    .filter((id) => existsSync(resolve(clientsDir, id, "config.ts")))
    .sort();
}

function buildRegistry() {
  const clientIds = listClientIds();
  if (clientIds.length === 0) {
    throw new Error("No client configs found in clients/");
  }

  const allEntries = clientIds.map((id) => {
    const configPath = resolve(clientsDir, id, "config.ts");
    const src = readFileSync(configPath, "utf8");
    const slug = readClientField(src, "slug") || id;
    const theme = readClientField(src, "theme") || "theme01";
    return {
      id,
      slug,
      theme,
      varName: configVarName(id),
      meta: readClientMeta(src),
      expiresAt: readClientField(src, "expiresAt"),
    };
  });

  const slugSet = new Set();
  for (const entry of allEntries) {
    if (RESERVED_SLUGS.has(entry.slug)) {
      throw new Error(`Reserved slug (테마 미리보기·사이트 폴더 이름): ${entry.slug} — clients/${entry.id}/config.ts`);
    }
    if (!SLUG_PATTERN.test(entry.slug)) {
      throw new Error(`Invalid slug (영문 소문자·숫자·-·_ 만): ${entry.slug} — clients/${entry.id}/config.ts`);
    }
    if (slugSet.has(entry.slug)) {
      throw new Error(`Duplicate client slug: ${entry.slug}`);
    }
    slugSet.add(entry.slug);
  }

  // 만료된 클라이언트는 빌드에서 제외 → 다음 배포부터 데이터 파일·프리렌더 페이지 자체가 사라짐.
  // slug 만 EXPIRED_SLUGS 로 남겨 '만료된 청첩장' 안내를 보여줌 (다른 청첩장으로 넘어가지 않게)
  const now = Date.now();
  const isExpired = (entry) => {
    const end = expiryEndMs(entry.expiresAt);
    return end !== null && now > end;
  };
  const expiredEntries = allEntries.filter(isExpired);
  const entries = allEntries.filter((entry) => !isExpired(entry));
  if (entries.length === 0) {
    throw new Error("All clients are expired");
  }
  if (expiredEntries.some((entry) => entry.id === DEFAULT_CLIENT_ID)) {
    throw new Error(`Default preview client ${DEFAULT_CLIENT_ID} must not have expiresAt`);
  }

  const imports = entries
    .map((entry) => `import ${entry.varName} from "../../../clients/${entry.id}/config";`)
    .join("\n");

  const configList = entries.map((entry) => entry.varName).join(", ");

  const bySlugEntries = entries
    .map((entry) => `  "${entry.slug}": ${entry.varName},`)
    .join("\n");

  const byIdEntries = entries
    .map((entry) => `  "${entry.id}": ${entry.varName},`)
    .join("\n");

  // 루트(/)·SPA 폴백 OG 메타용 기본 클라이언트 — 실제 고객 정보가 노출되지 않도록
  // 기본 미리보기(/grace)와 같은 샘플로 고정 (폴더명 알파벳순 첫 번째를 쓰지 않음)
  const defaultSlug =
    entries.find((entry) => entry.id === DEFAULT_CLIENT_ID)?.slug ?? entries[0].slug;

  const ts = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-client-registry.mjs — do not edit
import type { ClientConfig } from "../types";
${imports}

export const ALL_CLIENT_CONFIGS: readonly ClientConfig[] = [${configList}];

export const CLIENT_BY_SLUG: Record<string, ClientConfig> = {
${bySlugEntries}
};

export const CLIENT_BY_ID: Record<string, ClientConfig> = {
${byIdEntries}
};

export const DEFAULT_CLIENT_SLUG = "${defaultSlug}";
`;

  // 브라우저용 — 클라이언트별 config 를 따로 청크로 나눠, 접속한 청첩장 데이터만 내려받게 함
  // (client-registry.ts 는 모든 config 를 한 번에 import → Netlify 함수 등 서버 전용)
  const loaderEntries = entries
    .map(
      (entry) =>
        `  "${entry.slug}": () => import("../../../clients/${entry.id}/config").then((m) => m.default),`,
    )
    .join("\n");

  const loadersTs = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-client-registry.mjs — do not edit
import type { ClientConfig } from "../types";

export const CLIENT_LOADERS: Record<string, () => Promise<ClientConfig>> = {
${loaderEntries}
};

/** 접속 시 만료 확인용 (slug → "YYYY-MM-DD"). 만료일이 지나면 데이터를 불러오지 않음 */
export const CLIENT_EXPIRES_AT: Record<string, string> = {
${entries
  .filter((entry) => expiryEndMs(entry.expiresAt) !== null)
  .map((entry) => `  "${entry.slug}": "${entry.expiresAt}",`)
  .join("\n")}
};

/** 빌드 시점에 이미 만료되어 제외된 청첩장 slug */
export const EXPIRED_SLUGS: readonly string[] = ${JSON.stringify(expiredEntries.map((entry) => entry.slug))};

export const DEFAULT_CLIENT_SLUG = "${defaultSlug}";
`;

  const manifest = {
    defaultSlug,
    clients: entries.map(({ id, slug, theme, meta }) => ({ id, slug, theme, meta })),
    expiredSlugs: expiredEntries.map((entry) => entry.slug),
  };

  mkdirSync(outDir, { recursive: true });
  writeFileSync(outTs, ts, "utf8");
  writeFileSync(outLoaders, loadersTs, "utf8");
  writeFileSync(outManifest, JSON.stringify(manifest, null, 2), "utf8");

  console.log(
    `Generated client registry [${entries.map((e) => e.slug).join(", ")}]` +
      (expiredEntries.length ? ` (만료 제외: ${expiredEntries.map((e) => e.slug).join(", ")})` : "") +
      " → packages/shared/generated/",
  );
}

buildRegistry();
